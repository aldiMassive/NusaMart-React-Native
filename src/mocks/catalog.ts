export const mockProducts: Product[] = seeds.map((seed, index) => {
  const [
    name,
    description,
    price,
    originalPrice,
    categoryId,
    rating,
    soldCount,
    stock,
    featured,
  ] = seed
  const slug = name.toLowerCase().replace(/[^a-z0-9]+/g, '-')
  return {
    id: `product-${index + 1}`,
    name,
    slug,
    description,
    price,
    originalPrice,
    discountPercentage: Math.round(
      ((originalPrice - price) / originalPrice) * 100
    ),
    categoryId,
    images: [
      {
        id: `${index + 1}-main`,
        url: `https://picsum.photos/seed/${slug}/800/800`,
        alt: name,
      },
      {
        id: `${index + 1}-alt`,
        url: `https://picsum.photos/seed/${slug}-detail/800/800`,
        alt: `${name} detail`,
      },
    ],
    rating,
    reviewCount: Math.max(24, Math.round(soldCount * 0.42)),
    soldCount,
    stock,
    weight: 180 + index * 65,
    variants: index % 4 === 2 ? [] : colorVariant(stock),
    featured,
  }
})
